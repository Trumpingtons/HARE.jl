# Cross-validation of HARE.jl estimators and tests against R reference implementations.
#
# Strategy: data are generated once in Julia (StableRNG(42), n = 500) and
# written to CSV.  The R script below was run on those exact CSVs to produce
# the reference values hardcoded here.  No R installation is required to run
# these tests.
#
# R session used to produce reference values
# ──────────────────────────────────────────
# R version:         4.5.1
# prais version:     1.1.4   (prais::prais_winsten)
# orcutt version:    2.3     (orcutt::cochrane.orcutt)
# skedastic version: 2.0.3   (skedastic::harvey, skedastic::glejser)
#
# R script (reference/compute_r_reference.R):
# ────────────────────────────────────────────
# library(prais); library(orcutt); library(skedastic); library(nlme)
#
# ar  <- read.csv("hare_ref_ar.csv")    # generated by this file's @testset setup
# het <- read.csv("hare_ref_het.csv")
# exp <- read.csv("hare_ref_exp.csv")
# pow <- read.csv("hare_ref_pow.csv")
# gw  <- read.csv("hare_ref_gw.csv")
# gw$group <- factor(gw$group)
#
# ## iterated Prais-Winsten
# pw <- prais_winsten(y ~ x1 + x2, data = ar, index = "t")
# coef(pw)              # [0.807539364873110, 2.000888138176624, -0.995886386606774]
# pw$rho[length(pw$rho)]                 # 0.747516080408667
#
# ## two-step Prais-Winsten
# pw2 <- prais_winsten(y ~ x1 + x2, data = ar, index = "t", twostep = TRUE)
# coef(pw2)             # [0.807132250302464, 2.000733338521879, -0.995997001148784]
# pw2$rho[length(pw2$rho)]               # 0.741970716745227
#
# ## iterated Cochrane-Orcutt
# lm_ar <- lm(y ~ x1 + x2, data = ar)
# co <- cochrane.orcutt(lm_ar)
# coef(co)              # [0.804906554256083, 2.000952970585868, -0.995973850792775]
# co$rho                                 # 0.747510098037746
#
# ## Harvey test (het DGP, should reject)
# lm_het <- lm(y ~ x1 + x2, data = het)
# hv <- harvey(lm_het)
# as.numeric(hv$statistic)               # 122.011658302806
# as.numeric(hv$p.value)                 # 3.20261722852863e-27
# as.integer(hv$parameter)               # 2
#
# ## Glejser test (het DGP, should reject)
# gl <- glejser(lm_het)
# as.numeric(gl$statistic)               # 188.161183272780
# as.numeric(gl$p.value)                 # 1.38458045942223e-41
# as.integer(gl$parameter)               # 2
#
# ## Harvey test (AR data, homoskedastic, should not reject)
# lm_ar2 <- lm(y ~ x1 + x2, data = ar)
# hv_hom <- harvey(lm_ar2)
# as.numeric(hv_hom$statistic)           # 1.11269369998126
# as.numeric(hv_hom$p.value)             # 0.573299592428087
#
# ## Glejser test (AR data, homoskedastic, should not reject)
# gl_hom <- glejser(lm_ar2)
# as.numeric(gl_hom$statistic)           # 0.885866369071162
# as.numeric(gl_hom$p.value)             # 0.642150111212357
#
# ## exponential_mle vs nlme::gls(weights=varExp(form=~x1), method="ML")
# m <- gls(y ~ x1 + x2, data = exp, weights = varExp(form = ~x1), method = "ML")
# as.numeric(coef(m))
#   # [0.932932670183982, 1.969667861189314, -1.004532019132718]
# as.numeric(logLik(m))                        # -666.696087475518425
# # HARE gamma = (log sigma^2, 2*delta):
# log(m$sigma^2)                               # -0.109645546965486
# 2 * coef(m$modelStruct$varStruct, unconstrained=FALSE)  # 1.051704974663036
#
# ## power_mle vs nlme::gls(weights=varPower(form=~abs(x1)), method="ML")
# m <- gls(y ~ x1 + x2, data = pow, weights = varPower(form = ~abs(x1)), method = "ML")
# as.numeric(coef(m))
#   # [1.030580728301556, 1.972218700564740, -0.988014803197715]
# as.numeric(logLik(m))                        # -537.409276152191069
# log(m$sigma^2)                               # -0.068600899322008
# 2 * coef(m$modelStruct$varStruct, unconstrained=FALSE)  # 1.104458577099788
#
# ## groupwise_mle vs nlme::gls(weights=varIdent(form=~1|group), method="ML")
# m <- gls(y ~ x1 + x2, data = gw, weights = varIdent(form = ~1 | group), method = "ML")
# as.numeric(coef(m))
#   # [0.988926649135395, 2.050813417985083, -1.011995459361841]
# as.numeric(logLik(m))                        # -756.512639309266433
# sigma_ref <- m$sigma
# ratios <- c(1.0, coef(m$modelStruct$varStruct, unconstrained=FALSE))
# (sigma_ref * ratios)^2
#   # [0.275412406294380, 0.948016808963599, 2.000291616918291, 4.064414410886320]
#
# ## Beach-MacKinnon via nlme::gls (exact AR(1) ML, functional equivalent)
# library(nlme)                                         # nlme version: 3.1.168
# ar$t <- 1:nrow(ar)
# m <- gls(y ~ x1 + x2, data = ar,
#          correlation = corAR1(form = ~t), method = "ML")
# as.numeric(coef(m))
#   # [0.807429432370141, 2.000847350495754, -0.995915517086534]
# as.numeric(coef(m$modelStruct$corStruct, unconstrained = FALSE))
#   # 0.746041011460647
#
# Note: nlme uses a joint optimizer (Newton-Raphson) while HARE uses
# concentrated likelihood + Brent's method; both converge to the same MLE
# with differences of ~1.7e-9 in coef and ~2.2e-8 in rho.
#
# Note on test statistic formulas
# ────────────────────────────────
# skedastic uses Harvey's (1976) and Glejser's (1969) exact score-test formulas:
#   Harvey:  ESS / trigamma(1/2)        where trigamma(1/2) = π²/2 = Var(log χ²(1))
#   Glejser: ESS_|û| / (σ̂²·(1−2/π))   where (1−2/π) = Var(|N(0,1)|)
# HARE uses the same formulas, so statistics agree to machine precision.

using Test
using HARE
using StableRNGs
using LinearAlgebra
using StatsBase

@testset "R cross-validation" begin

    # ── shared data (must match the R script above) ───────────────────────────
    rng = StableRNG(42)
    n   = 500

    x1 = randn(rng, n)
    x2 = randn(rng, n)
    X      = hcat(x1, x2)
    X_full = hcat(ones(n), x1, x2)
    b_true = [1.0, 2.0, -1.0]

    eps  = randn(rng, n)
    u_ar = zeros(n)
    for t in 2:n; u_ar[t] = 0.7 * u_ar[t-1] + eps[t]; end
    y_ar = X_full * b_true .+ u_ar

    sigma_h = exp.(0.5 .* x1)
    y_het   = X_full * b_true .+ sigma_h .* randn(rng, n)

    rng_mle = StableRNG(99)              # separate stream so MLE data is independent of AR/het data

    sigma_exp = exp.(0.5 .* x1)         # log σ²_i = 0 + 1·x1
    y_exp     = X_full * b_true .+ sigma_exp .* randn(rng_mle, n)

    sigma_pow = abs.(x1) .^ 0.5         # σ²_i = |x1|  (γ₀=0, γ₁=1, δ=0.5)
    y_pow     = X_full * b_true .+ sigma_pow .* randn(rng_mle, n)

    gw_groups = repeat(["A","B","C","D"], inner = n ÷ 4)
    gw_sig    = Dict("A"=>0.5,"B"=>1.0,"C"=>1.5,"D"=>2.0)
    y_gw      = X_full * b_true .+ [gw_sig[g] for g in gw_groups] .* randn(rng_mle, n)

    # ── R reference values ────────────────────────────────────────────────────
    r_pw_coef  = [0.807539364873110,  2.000888138176624, -0.995886386606774]
    r_pw_rho   =  0.747516080408667

    r_pw2_coef = [0.807132250302464,  2.000733338521879, -0.995997001148784]
    r_pw2_rho  =  0.741970716745227

    r_co_coef  = [0.804906554256083,  2.000952970585868, -0.995973850792775]
    r_co_rho   =  0.747510098037746

    r_harvey_het_stat  = 122.011658302806
    r_harvey_het_pval  = 3.20261722852863e-27
    r_harvey_het_dof   = 2

    r_glejser_het_stat = 188.161183272780
    r_glejser_het_pval = 1.38458045942223e-41
    r_glejser_het_dof  = 2

    r_harvey_hom_stat  = 1.11269369998126
    r_harvey_hom_pval  = 0.573299592428087

    r_glejser_hom_stat = 0.885866369071162
    r_glejser_hom_pval = 0.642150111212357

    r_bm_coef = [0.807429432370141,  2.000847350495754, -0.995915517086534]
    r_bm_rho  =  0.746041011460647

    r_exp_coef   = [0.976294837716426,  1.993398568287984, -1.011490745818754]
    r_exp_loglik = -694.669454326422
    r_exp_gamma  = [0.003905013533464,  1.080067111842661]  # (log σ², 2δ)

    r_pow_coef   = [0.995527027350956,  2.115026142884222, -0.963949778439413]
    r_pow_loglik = -565.804191733345
    r_pow_gamma  = [-0.039018137343397, 0.954740616024428]  # (log σ², 2δ)

    r_gw_coef   = [0.999997707147934,  1.974047597189269, -0.941274618422628]
    r_gw_loglik = -725.147180017231
    r_gw_sigma2 = [0.274319917149154,  0.757623193539298,  1.950196799526272, 3.170678872290372]

    # ── iterated Prais-Winsten vs prais::prais_winsten() ─────────────────────
    @testset "iterated_prais_winsten vs R (prais 1.1.4)" begin
        m = iterated_prais_winsten(X, y_ar)
        @test coef(m) ≈ r_pw_coef  atol=1e-6
        @test m.rho   ≈ r_pw_rho   atol=1e-6
    end

    # ── two-step Prais-Winsten vs prais::prais_winsten(twostep=TRUE) ──────────
    @testset "two_step_prais_winsten vs R (prais 1.1.4)" begin
        m = two_step_prais_winsten(X, y_ar)
        @test coef(m) ≈ r_pw2_coef atol=1e-6
        @test m.rho   ≈ r_pw2_rho  atol=1e-6
    end

    # ── iterated Cochrane-Orcutt vs orcutt::cochrane.orcutt() ────────────────
    @testset "iterated_cochrane_orcutt vs R (orcutt 2.3)" begin
        m = iterated_cochrane_orcutt(X, y_ar)
        @test coef(m) ≈ r_co_coef  atol=1e-6
        @test m.rho   ≈ r_co_rho   atol=1e-6
    end

    # ── Harvey test vs skedastic::harvey() ───────────────────────────────────
    @testset "harvey_test vs R (skedastic 2.0.3)" begin
        t_het = harvey_test(X, y_het)
        @test t_het.lm  ≈ r_harvey_het_stat  atol=1e-6
        @test pvalue(t_het) ≈ r_harvey_het_pval rtol=1e-6
        @test t_het.dof == r_harvey_het_dof

        t_hom = harvey_test(X, y_ar)
        @test t_hom.lm  ≈ r_harvey_hom_stat  atol=1e-6
        @test pvalue(t_hom) ≈ r_harvey_hom_pval rtol=1e-6
    end

    # ── Glejser test vs skedastic::glejser() ─────────────────────────────────
    @testset "glejser_test vs R (skedastic 2.0.3)" begin
        t_het = glejser_test(X, y_het)
        @test t_het.lm  ≈ r_glejser_het_stat  atol=1e-6
        @test pvalue(t_het) ≈ r_glejser_het_pval rtol=1e-6
        @test t_het.dof == r_glejser_het_dof

        t_hom = glejser_test(X, y_ar)
        @test t_hom.lm  ≈ r_glejser_hom_stat  atol=1e-6
        @test pvalue(t_hom) ≈ r_glejser_hom_pval rtol=1e-6
    end

    # ── exponential_mle vs nlme::gls(varExp, method="ML") ───────────────────
    # nlme: Var(εᵢ) = σ²·exp(2δ·x₁ᵢ)  ↔  HARE: log σ²ᵢ = γ₀ + γ₁·x₁ᵢ
    # Same likelihood; γ₀ = log σ²_nlme, γ₁ = 2δ_nlme
    @testset "exponential_mle vs R (nlme 3.1.168, varExp)" begin
        m = exponential_mle(X, y_exp; Z = hcat(x1))
        @test coef(m)    ≈ r_exp_coef   atol=1e-4
        @test m.loglik   ≈ r_exp_loglik atol=1e-3
        @test m.gamma    ≈ r_exp_gamma  atol=1e-4
        @test m.converged
    end

    # ── power_mle vs nlme::gls(varPower, method="ML") ────────────────────────
    # nlme: Var(εᵢ) = σ²·|x₁ᵢ|^{2δ}  ↔  HARE: log σ²ᵢ = γ₀ + γ₁·log|x₁ᵢ|
    # Same likelihood; γ₀ = log σ²_nlme, γ₁ = 2δ_nlme
    @testset "power_mle vs R (nlme 3.1.168, varPower)" begin
        m = power_mle(X, y_pow; Z = hcat(abs.(x1)))
        @test coef(m)    ≈ r_pow_coef   atol=1e-4
        @test m.loglik   ≈ r_pow_loglik atol=1e-3
        @test m.gamma    ≈ r_pow_gamma  atol=1e-4
        @test m.converged
    end

    # ── groupwise_mle vs nlme::gls(varIdent, method="ML") ───────────────────
    @testset "groupwise_mle vs R (nlme 3.1.168, varIdent)" begin
        m = groupwise_mle(X, y_gw, gw_groups)
        @test coef(m)    ≈ r_gw_coef   atol=1e-4
        @test m.loglik   ≈ r_gw_loglik atol=1e-3
        @test m.sigma2   ≈ r_gw_sigma2 atol=1e-3
        @test m.converged
    end

    # ── Beach-MacKinnon vs nlme::gls(corAR1(), method="ML") ──────────────────
    # nlme uses a joint Newton-Raphson optimizer; HARE uses concentrated
    # likelihood + Brent's method.  Both maximise the same exact AR(1) log-
    # likelihood, so they agree to ~1e-8 (different solver paths, same MLE).
    @testset "beach_mackinnon vs R (nlme 3.1.168)" begin
        m = beach_mackinnon(X, y_ar)
        @test coef(m) ≈ r_bm_coef  atol=1e-5
        @test m.rho   ≈ r_bm_rho   atol=1e-5
    end

end
